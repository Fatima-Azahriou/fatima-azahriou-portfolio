-- Run this entire script in Supabase Dashboard > SQL Editor.
create table if not exists public.recommendations (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  role text not null check (char_length(role) between 2 and 140),
  relationship text not null check (char_length(relationship) between 2 and 160),
  recommendation text not null check (char_length(recommendation) between 30 and 2000),
  email text not null check (char_length(email) between 5 and 254),
  permission boolean not null default false check (permission = true),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.recommendations enable row level security;

-- Visitors can read approved recommendations only.
drop policy if exists "Anyone can read approved recommendations" on public.recommendations;
create policy "Anyone can read approved recommendations"
  on public.recommendations for select
  to anon, authenticated
  using (status = 'approved');

-- Visitors can submit pending recommendations only.
drop policy if exists "Anyone can submit pending recommendations" on public.recommendations;
create policy "Anyone can submit pending recommendations"
  on public.recommendations for insert
  to anon, authenticated
  with check (status = 'pending' and permission = true);

-- No public update/delete policies: moderation happens in the Supabase dashboard by the owner.
